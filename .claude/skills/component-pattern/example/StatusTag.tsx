import { Tag, type TagProps } from 'antd';

/**
 * Статусы, которые метка умеет показывать.
 *
 * Тип объявлен здесь, а не в `types/`: за пределами пропсов `StatusTag` он
 * никому не нужен, а рядом с компонентом он читается вместе с ним.
 */
export type StatusKind = 'active' | 'blocked' | 'pending';

/**
 * Цвет на статус — таблицей, а не цепочкой `if`.
 *
 * Соответствие «статус → цвет» и есть всё правило целиком, и таблица показывает
 * его одним взглядом: новый статус добавляется строкой, а не ещё одной веткой,
 * и tsc сам укажет на забытую, потому что `Record` требует все ключи.
 *
 * Имена цветов — пресеты antd: они уже завязаны на тему и в тёмной схеме
 * меняются сами. Свой `#52c41a` этого не умеет.
 */
const STATUS_COLOR: Record<StatusKind, TagProps['color']> = {
  active: 'green',
  blocked: 'red',
  pending: 'gold',
};

/**
 * Слоты `Tag` — `root`, `icon`, `content`, `close` — без функциональной формы.
 *
 * У antd `styles` бывает и функцией, считающей слоты по пропсам. Обёртка кладёт
 * в этот проп своё, а слить функцию spread'ом нельзя: `{ ...styles }` от неё даст
 * пустой объект и молча потеряет её целиком. Поэтому принимается только объект —
 * `Exclude` убирает вторую форму на уровне типа, и панель узнает об этом от tsc,
 * а не по пропавшим стилям.
 */
type TagStyles = Exclude<NonNullable<TagProps['styles']>, (info: never) => unknown>;

/**
 * Пропсы объявлены над компонентом — в том же файле и сразу после импортов.
 *
 * Отдельного файла типов у пропсов нет: пропсы — подпись компонента, и
 * разнесённые по двум файлам они молча расходятся.
 */
export interface StatusTagProps extends Omit<TagProps, 'styles'> {
  /** Статус, который метка показывает. Определяет цвет. */
  status: StatusKind;
  /** Подпись вместо самого статуса — например, переведённая. */
  label?: string;
  /** Стили частей метки. Кладутся поверх своих. */
  styles?: TagStyles;
}

/**
 * Цветная метка статуса сущности.
 *
 * Обёртка над antd `Tag`: своё — только соответствие статуса цвету, остальное
 * уходит в базу через `...rest`.
 *
 * @example
 * ```tsx
 * <StatusTag status="active" label={t('active')} />
 * ```
 */
export const StatusTag = (props: StatusTagProps) => {
  const { status, label, style, styles, ...rest } = props;

  return (
    <Tag
      color={STATUS_COLOR[status]}
      /*
       * Внешний вид задаётся `style` и `styles` самого antd-компонента. CSS-файла
       * и `className` у компонента нет: класс живёт в другом файле и молча
       * разъезжается с разметкой, а из панели его не перекрыть — там, где стиль
       * приходит пропом, панель просто передаёт свой.
       *
       * `style` — корень, `styles` — части внутри него: у `Tag` это `root`,
       * `icon`, `content` и `close`.
       */
      style={{ whiteSpace: 'nowrap', ...style }}
      /*
       * Крестик наследует цвет статуса: `closable` приходит снаружи через
       * `rest`, а своим блёклым серым antd рисует его поверх цветного тега.
       */
      styles={{ close: { color: 'inherit' }, ...styles }}
      {...rest}
    >
      {label ?? status}
    </Tag>
  );
};
