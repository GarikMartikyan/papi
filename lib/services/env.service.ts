import { warn } from '../utils/logger.util';

/**
 * Единственное место, где ядро читает переменные окружения.
 *
 * Собрано в сервисе, а не разложено по местам использования: подстановка
 * дефолта и предупреждение о ненастроенном окружении должны выглядеть
 * одинаково для любой переменной, а разложенные по файлам они разойдутся.
 */

/** Без переменной запросы уходят на тот же origin, откуда открыта панель. */
const FALLBACK_API_BASE_URL = '/';

/**
 * Про ненастроенное окружение сообщаем один раз на переменную. `baseQuery`
 * спрашивает адрес однажды, при загрузке модуля, но панель вправе позвать
 * геттер и на рендере — тогда без этого множества одинаковая строка забила бы
 * консоль.
 */
const warnedNames = new Set<string>();

/**
 * Значение переменной или `fallback`, если её не задали.
 *
 * Значение приходит параметром, а не читается здесь по имени: `vite/client`
 * объявляет `import.meta.env` индексной сигнатурой `any`, и чтение по
 * переменному ключу вернуло бы `any` вместо типа из `lib/vite-env.d.ts`.
 * Обращение к свойству на стороне геттера эту типизацию сохраняет.
 */
const readEnv = (name: string, value: string | undefined, fallback: string): string => {
  if (value !== undefined && value !== '') return value;

  if (!warnedNames.has(name)) {
    warnedNames.add(name);
    warn(`${name} is not set — falling back to "${fallback}".`);
  }

  return fallback;
};

/**
 * Префикс, который приписывается ко всем путям эндпоинтов.
 *
 * Берётся из окружения, а не из вызова панели: адрес известен на сборке и на
 * рантайме не меняется, а второе место, где его можно задать, рано или поздно
 * разойдётся с `.env` — и разойдётся молча.
 *
 * Переменная объявлена в `lib/vite-env.d.ts`, значение по умолчанию —
 * в `.env.example`.
 *
 * Выходит наружу, потому что адрес нужен и вне RTK Query — на ссылку в новой
 * вкладке или на `src` картинки. Собирать его там из переменной заново значит
 * завести второй источник правды.
 */
export const getApiBaseUrl = (): string => {
  return readEnv('VITE_API_BASE_URL', import.meta.env.VITE_API_BASE_URL, FALLBACK_API_BASE_URL);
};
