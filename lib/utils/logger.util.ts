/**
 * Предупреждения библиотеки — с общим префиксом, чтобы в консоли панели было
 * видно, откуда сообщение.
 *
 * Используется там, где некорректное значение не ломает работу, а молча
 * заменяется дефолтом: без сообщения такие подмены невозможно заметить.
 *
 * Только для внутреннего использования: наружу не экспортируется (см.
 * `utils/index.ts`) — префикс `[papi]` в сообщении панели врал бы про источник.
 * Внутри ядра импортируется напрямую из этого файла, а не из барреля.
 */
export const warn = (message: string): void => {
  console.warn(`[papi] ${message}`);
};
