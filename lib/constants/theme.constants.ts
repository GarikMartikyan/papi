/*
 * Значения темы, которые нужны не только самой теме: их берут ещё и компоненты
 * ядра напрямую. Всё остальное — радиусы, цвета — живёт внутри
 * `theme/base.theme.ts`, оттуда их читает один antd.
 */

/**
 * Фон блока, лежащего на странице: карточки, сайдбары, контролы в шапке.
 * Страница остаётся светлее, внутри карточки таблица снова белая.
 *
 * Затемнение, а не осветление: блок всегда темнее подложки — и в светлой теме,
 * и в тёмной. Токены-заливки antd (`colorFillSecondary` и соседние) для этого
 * не годятся, они в тёмной теме переворачиваются в белый оверлей и делают блок
 * светлее страницы.
 *
 * Плотность разная: 6% на светлой подложке уже читаются, а на тёмной почти
 * пропадают, поэтому там 19% — это `#00000030` в rgba.
 *
 * `light-dark()`, а не два значения по режимам: antd отдаёт значение токена в
 * `background` как есть, а режим браузер берёт из `color-scheme` на <html> —
 * его ставит `ThemeProvider`. Так тема остаётся одним статичным объектом.
 *
 * @example
 * ```tsx
 * <Card style={{ background: BLOCK_BG, borderRadius: BLOCK_RADIUS }} />
 * ```
 */
export const BLOCK_BG = 'light-dark(rgba(0, 0, 0, 0.06), rgba(0, 0, 0, 0.19))';

/**
 * Скругление блока, лежащего на странице: навигации и карточек — тех же, что
 * стоят на `BLOCK_BG`. Форма у них общая, поэтому и радиус один.
 *
 * Своё значение, а не `borderRadiusLG` темы: на нём висят ещё диалоги,
 * всплывающие панели и пункты меню, а такая мягкость нужна только блокам.
 *
 * Числом, а не строкой: значение уходит в `style`, и пиксели React дописывает сам.
 */
export const BLOCK_RADIUS = 26;
