import type { MessageDescriptor } from 'react-intl';

import type { Locale, LocaleMessages } from '../types/types/i18n.type';

import enMessages from './en.json';
import ruMessages from './ru.json';

/**
 * Переводы строк самого ядра — по языку.
 *
 * Ядро возит их, чтобы панель не перепечатывала у себя два десятка строк входа
 * и ошибок: раньше без этого любой язык, кроме английского, был работой панели,
 * и добавленная в ядре строка молча оставалась непереведённой до тех пор, пока
 * кто-нибудь не заметит её в интерфейсе.
 *
 * Список языков это по-прежнему не задаёт — его задаёт панель, `I18nConfig`.
 * Здесь лежит только то, что ядро умеет сказать на своей стороне.
 *
 * `I18nProvider` подкладывает каталог отсюда **под** каталог панели, поэтому
 * одноимённый ключ в её `messages` перекрывает строку ядра — так панель меняет
 * формулировку, не трогая `lib/`. Английский он подкладывает ещё ниже, самым
 * первым слоем: язык, которого в каталогах ядра нет, показывает строки ядра
 * по-английски, а не голым ключом.
 */
export const PAPI_CATALOGS: Readonly<Record<Locale, LocaleMessages>> = {
  en: enMessages,
  ru: ruMessages,
};

/**
 * Ключи строк ядра — из английского каталога.
 *
 * Английский, а не какой-то ещё: он источник этих строк, остальные языки могут
 * от него отставать. TS выводит из JSON литеральный union, поэтому опечатка в
 * ключе не доживает до рантайма.
 *
 * Панели он нужен, чтобы дописать строки ядра к своим: в рантайме каталоги
 * склеены, и `t('sign out')` из панели работает — но её собственный union про
 * этот ключ не знает. См. `src/hooks/useTranslation.ts`.
 */
export type PapiMessageKey = keyof typeof enMessages;

/**
 * Ключ строки ядра → дескриптор для тех мест, где ключ едет данными.
 *
 * Нужен там, где строка выбирается вне React и хранится до показа: разобранная
 * ошибка запроса (`PapiApiError`), настройки тостов у эндпоинта
 * (`PapiQueryExtraOptions`). В этих местах рядом с ключом лежит и готовый текст
 * от бэкенда, который переводить нечем и не надо, — и объект отличает одно от
 * другого: строка показывается как есть, дескриптор идёт в `t`.
 *
 * Обёртка, а не литерал `{ id: '...' }` на месте: `MessageDescriptor['id']` —
 * обычный `string | number`, и опечатку в нём никто не поймает. Здесь ключ
 * сверяется с каталогом.
 */
export const papiMessage = (key: PapiMessageKey): MessageDescriptor => ({ id: key });
