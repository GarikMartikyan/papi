/**
 * Контракт сессии: что уходит на `/auth/*` и что оттуда приходит.
 *
 * Три формы одним файлом, потому что порознь они не читаются: это два конца
 * одних и тех же запросов. Адреса лежат у ручек (`api/endpoints/auth.api`),
 * здесь только формы.
 */

/** Что форма входа отправляет на `POST /auth/login`. */
export interface LoginPayload {
  /**
   * Логин или почта — бэкенд принимает и то, и другое в одном поле и ищет по
   * обоим без учёта регистра.
   */
  username: string;
  /** Пароль как есть: шифрует его канал, а не панель. */
  password: string;
  /**
   * Панель, в которую входят. Заполняется ядром из `getPanelKey()`, форме его
   * передавать не нужно.
   */
  panelKey: string;
}

/**
 * Что бэкенд отвечает на удачный вход и на удачную ротацию — ответ у них один.
 */
export interface AuthTokens {
  /** Токен доступа. Уходит в `Authorization: Bearer …` на каждом запросе. */
  accessToken: string;
  /**
   * Токен обновления. Одноразовый: ротация выдаёт новый, а предъявленный второй
   * раз бэкенд считает кражей и отзывает всю семью токенов этой сессии.
   */
  refreshToken: string;
  /** Сколько секунд жив токен доступа. Ядро не использует — ротация идёт по 401. */
  expiresIn: number;
  /*
   * TODO: заглушка — поле приходит, но не используется. Заменить на переход
   * к экрану смены пароля, когда он появится: при `true` человек вошёл по
   * временному паролю, и до смены его в панель пускать нельзя.
   */
  mustChangePassword: boolean;
}

/** Что уходит на `POST /auth/refresh` и `POST /auth/logout`. */
export interface RefreshTokenPayload {
  refreshToken: string;
}
