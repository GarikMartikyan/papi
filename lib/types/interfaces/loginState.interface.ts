/**
 * Что гард кладёт в `state`, уводя неавторизованного на вход.
 *
 * Нужно, чтобы после входа человек вернулся туда, куда шёл, а не на первую
 * страницу: ссылку на конкретную запись обычно и присылают.
 */
export interface PapiLoginState {
  /**
   * Адрес, на который человек шёл до того, как гард увёл его на вход, — один
   * путь: гард берёт его из `useLocation().pathname`, поэтому ни query, ни
   * хеша в нём нет. Нет адреса — после входа открывается первый маршрут
   * панели.
   */
  from?: string;
}
