import type { Locale } from '../types/i18n.type';

import type { LocaleDefinition } from './localeDefinition.interface';

/**
 * Языки панели целиком: список и то, какой из них запасной.
 *
 * Выделенного языка у ядра нет. Раньше английский был зашит: его локали лежали
 * в papi, он всегда подмешивался в список и служил запасным — из-за чего панель
 * не могла ни собрать сборку без него, ни сделать запасным другой язык.
 * Теперь и список, и запасной приходят отсюда.
 */
export interface I18nConfig {
  /**
   * Запасной язык: на него уходят незнакомые значения из localStorage и он же
   * идёт в `defaultLocale` react-intl, то есть отвечает за строки без перевода.
   *
   * Должен быть среди `locales` — иначе papi предупредит и возьмёт первый.
   */
  default: Locale;
  /** Все языки панели, включая запасной. */
  locales: readonly LocaleDefinition[];
}
