/**
 * Сессия пользователя, которой владеет слайс `auth`.
 *
 * Токены и в сторе, и в localStorage: из хранилища их читают `baseQuery` и
 * `refreshSession` — они вызываются вне React и до стора не дотягиваются, — а
 * из стора их читает интерфейс, которому нужно перерисоваться на входе и
 * выходе. Единственное место, где они расходятся, — редьюсеры слайса, и они
 * пишут в оба.
 *
 * Токена два, потому что их два у papi-authority, и роли у них разные: коротким
 * `accessToken` подписан каждый запрос, а длинный `refreshToken` только меняется
 * на новую пару, когда первый истёк. Порознь они не живут — ни один редьюсер не
 * трогает одно поле, не тронув второе.
 */
export interface AuthState {
  /**
   * Токен доступа. Уходит в `Authorization: Bearer …`. Живёт минуты, поэтому
   * запрос с ним рутинно отвечает 401 — это не конец сессии, а повод
   * обновиться.
   */
  accessToken: string | null;
  /**
   * Токен обновления. Не уходит никуда, кроме `/auth/refresh` и `/auth/logout`.
   * `null` — сессии нет: продлить её нечем, и следующий 401 станет выходом.
   */
  refreshToken: string | null;
}
