/**
 * Сессия пользователя, которой владеет слайс `auth`.
 *
 * Токен и в сторе, и в localStorage: из хранилища его читает `baseQuery` перед
 * каждым запросом — он вызывается вне React и до стора не дотягивается, — а из
 * стора его читает интерфейс, которому нужно перерисоваться на входе и выходе.
 * Единственное место, где они расходятся, — редьюсеры слайса, и они пишут в оба.
 */
export interface AuthState {
  /** `null` — пользователь не вошёл. Ни один маршрут панели ему не откроется. */
  token: string | null;
}
