import type { CSSProperties, HTMLAttributes } from 'react';

import logoLarge from '../../assets/images/logo-large.svg';
import { usePapiTranslation } from '../../hooks/usePapiTranslation';
import { useThemeToken } from '../../hooks/useThemeToken';

/**
 * Пропорции логотипа 124:49, поэтому ширина считается от высоты, а не задаётся.
 *
 * Крупнее, чем 52 на входных экранах: там логотип стоит над карточкой и делит
 * с ней внимание, здесь он один на всё окно, и в том же размере выглядел бы
 * потерянным.
 */
const LOGO_HEIGHT = 64;

/**
 * Своя высота на весь экран: экран стоит вместо каркаса, а `100vh` держит тот.
 * Без неё содержимое прижалось бы к верхнему краю.
 *
 * Отступ — на случай содержимого пошире крутилки: у сообщения об ошибке есть
 * текст, и на узком экране он не должен упираться в края.
 */
const PAGE_STYLE: CSSProperties = {
  alignItems: 'center',
  display: 'flex',
  justifyContent: 'center',
  minHeight: '100vh',
  padding: 24,
};

const LOGO_STYLE: CSSProperties = { display: 'block' };

export interface SplashScreenProps extends HTMLAttributes<HTMLDivElement> {
  /**
   * Свой логотип вместо логотипа ядра — тот же проп, что у `AuthLayout`, и с
   * тем же смыслом: панель показывает своё лицо, а ждёт по-нашему.
   */
  logo?: string;
}

/**
 * Экран на всё окно: панели ещё нечего показать.
 *
 * Так выглядит ожидание до каркаса — пока гард `PapiRouter` спрашивает у
 * бэкенда, жива ли сессия. Каркас в это время не рисуется намеренно: шапка с
 * меню, мелькнувшие перед уходом на вход, читаются сбоем, а не загрузкой.
 *
 * Без содержимого это логотип, в который наливается цвет, поэтому обычному
 * ожиданию хватает `<SplashScreen />`. Логотип, а не крутилка: экран занимает
 * всё окно на секунду-другую после входа, и на нём человек должен узнать то
 * место, куда шёл, а не увидеть безымянный кружок. Заливка говорит остальное —
 * что идёт загрузка, а не сломался рендер.
 *
 * Логотипов два, один поверх другого: нижний обесцвечен, верхний открывается
 * бегущей маской. Как это устроено и почему кромка размытая — в `styles.css`,
 * рядом с `papi-splash`.
 *
 * Текста здесь нет: экран живёт доли секунды на быстрой сети, и подпись успела
 * бы только мигнуть. Нужна своя — она передаётся как `children`.
 *
 * Переданные `children` встают вместо логотипа — так же посередине пустого
 * экрана; тем же местом пользуются экран ошибки гарда и страницы результата вне
 * каркаса (404, 403).
 *
 * Панели он пригодится под `Suspense` вокруг лениво подгружаемых страниц: там
 * нужен ровно такой экран — ничего, кроме признака, что идёт загрузка.
 */
export const SplashScreen = (props: SplashScreenProps) => {
  const { children, logo = logoLarge, style, ...rest } = props;

  const t = usePapiTranslation();

  const token = useThemeToken();

  return (
    <div style={{ ...PAGE_STYLE, background: token.colorBgContainer, ...style }} {...rest}>
      {children ?? (
        /* `progressbar` без значений — то есть неопределённый: сколько осталось
           ждать, не знает и сам экран. Подпись у него всё же есть: читающий с
           экрана иначе получил бы пустую страницу без единого слова о том, что
           происходит. Роль на обёртке, а не на картинках: заливка — один
           индикатор, просто собранный из двух слоёв.

           `alt` у обеих пуст намеренно: подпись уже дана обёрткой, а название
           панели человек слышал в заголовке страницы. */
        <div className="papi-splash" role="progressbar" aria-label={t('loading')}>
          <img
            className="papi-splash-base"
            src={logo}
            alt=""
            height={LOGO_HEIGHT}
            style={LOGO_STYLE}
          />
          <img
            className="papi-splash-fill"
            src={logo}
            alt=""
            height={LOGO_HEIGHT}
            style={LOGO_STYLE}
          />
        </div>
      )}
    </div>
  );
};
