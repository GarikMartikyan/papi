/**
 * Components — shared UI built on antd: layout, navigation, feedback, guards.
 *
 * Папок две. В `layouts/` — каркасы страницы; каждый лежит своей папкой, где
 * сам каркас в корне, а его части — в `elements/`. В `shared/` — компоненты,
 * которые вставляются куда угодно и о каркасе ничего не знают; они лежат
 * файлами прямо в папке, без своей папки на каждый: части у них нет, и папка
 * вокруг одного файла добавляла бы уровень, ничего не разделяя.
 *
 * Каркасов два, и они не пересекаются: `MainLayout` — панель целиком, шапка с
 * колонками вокруг страницы, `AuthLayout` — входные экраны, которые стоят вне
 * панели: кадры на весь экран и карточка по центру. Панель собирает каждый
 * одним компонентом и передаёт всё пропсами. Их части из `elements/` наружу не
 * выходят — самостоятельными компонентами они не являются, поэтому в барели их
 * нет.
 *
 * `LocaleSelect`, `ThemeSwitcher` и `UserMenu` выходят наружу отдельно: в шапку
 * их ставит сам `MainLayout`, но панель может показать их ещё раз — например
 * переключатель на странице настроек или аватар в своей шапке.
 *
 * `SplashScreen` — ожидание на весь экран, до всякого каркаса. Ядро показывает
 * его, пока гард проверяет сессию; панели он нужен под `Suspense` вокруг
 * лениво подгружаемых страниц.
 *
 * `LogoTemplate` — шаблон логотипа: пилюля с иконкой панели, буквами из
 * `VITE_APP_ABBR` и именем из `VITE_APP_NAME`, в трёх размерах. Для панели, у
 * которой своего логотипа ещё нет. Каркасы его не ставят — у них картинка
 * ядра и проп `logo`; панель показывает его там, где решит сама.
 *
 * `PanelLogo` — он же, но для панели из каталога: `panel="rmp"` вместо трёх
 * брендовых пропсов. Сам каталог лежит там же, рядом с компонентом.
 *
 * Барель на всю папку один: `@papi/components` — то, что панель видит, и делить
 * его по подпапкам незачем, границы `layouts`/`shared` внутренние.
 */

