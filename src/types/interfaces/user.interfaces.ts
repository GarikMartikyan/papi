/**
 * Пользователь панели.
 *
 * TODO: заглушка — раздела пользователей у скелета нет, форма заведена под
 * эталонный пример ручек (`.claude/skills/api-endpoint-pattern/example/users.api.ts`).
 * Панель заменяет её своей, когда бэкенд объявит контракт.
 *
 * Лежит здесь, а не в `users.api.ts`: сущность одной ручкой не ограничивается —
 * её показывает таблица, правит форма, принимает хук. Объявленная рядом с
 * ручками, она превращает файл ручек в модуль типов, и следующий, кому нужен
 * `User`, берёт его оттуда — привязываясь не к сущности, а к тому месту, откуда
 * данные однажды пришли.
 */
export interface User {
  /** Идентификатор. По нему адрес карточки и ключ строки в таблице. */
  id: string;
  /** Отображаемое имя — подпись в списке и заголовок карточки. */
  name: string;
  /** Почта. У papi-authority она же служит логином. */
  email: string;
  /** Роль одной строкой — так её отдаёт список. */
  role: string;
}
