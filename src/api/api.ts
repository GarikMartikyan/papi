import { configureApi } from '@papi/api';

/**
 * Единственная настройка api на всю панель.
 *
 * Теги передаются здесь, а не в файлах эндпоинтов: `createApi` внутри ядра
 * фиксирует набор тегов при создании, поэтому расширить его можно только тут —
 * и результат нужно использовать вместо `baseApi`.
 *
 * Стор ядра уже зарегистрировал редьюсер и middleware baseApi, так что панели
 * ничего подключать не нужно.
 *
 * TODO: заглушка — тегов у скелета нет, эндпоинтов тоже. Панель перечисляет
 * свои в `tagTypes` и добавляет файлы эндпоинтов рядом:
 * `api.injectEndpoints({ … })`.
 */
export const api = configureApi({
  baseUrl: import.meta.env.VITE_API_BASE_URL ?? '/api/v1',
  tagTypes: [],
});
