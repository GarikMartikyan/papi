import { useTranslation as usePapiTranslation } from '@papi/hooks';
import type { PapiMessageKey } from '@papi/i18n';

import type enMessages from '../i18n/en.json';

/**
 * Ключи сообщений, доступные панели: свои плюс строки ядра.
 *
 * Свои — из `en.json`, потому что он объявлен в `I18nConfig.default`: этот язык
 * переведён всегда, остальные могут отставать. TS выводит из JSON литеральный
 * union, поэтому опечатка в ключе не доживёт до рантайма.
 *
 * Строки ядра — потому что в рантайме каталоги склеены, и `t('sign out')`
 * работает независимо от того, есть ли этот ключ у панели. Перепечатывать
 * «Выйти», «Повторить» и «Почта» у себя, когда ядро уже сказало это на обоих
 * языках, незачем — ключом стал сам текст, и совпадение теперь видно глазом.
 *
 * Обратная сторона: переименованная в ядре строка ломает панель. Ломает на
 * компиляции — union перестанет её содержать, — а не в интерфейсе, поэтому это
 * терпимо. Панели, которой нужна независимость от формулировки ядра, ничто не
 * мешает завести ключ у себя: одноимённый перекрывает строку ядра.
 */
export type MessageKey = keyof typeof enMessages | PapiMessageKey;

/**
 * `t` с проверкой ключей. Ядро типизировать их само не может — см. `@papi/hooks`.
 *
 * Отдаёт саму функцию: `const t = useTranslation()`.
 */
export const useTranslation = () => usePapiTranslation<MessageKey>();
